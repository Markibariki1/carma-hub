#!/usr/bin/env node
/**
 * Delete prospect drafts whose link has expired: the JSON in content/prospects
 * and the images in public/fuer/<token>/. Then refresh content/prospects/index.ts.
 * Runs daily in the "Prospect pages" GitHub Action; safe to run by hand too.
 */
import { readdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = path.join(ROOT, 'content', 'prospects');
const DAY = 24 * 60 * 60 * 1000;

let removed = 0;
for (const f of (await readdir(dataDir)).filter((x) => x.endsWith('.json'))) {
  const p = JSON.parse(await readFile(path.join(dataDir, f), 'utf8'));
  const ends = new Date(p.created).getTime() + (p.days ?? 30) * DAY;
  if (Date.now() > ends) {
    await rm(path.join(dataDir, f));
    await rm(path.join(ROOT, 'public', 'fuer', p.token), { recursive: true, force: true });
    console.log(`Removed expired draft for ${p.business} (${p.token})`);
    removed++;
  }
}

const files = (await readdir(dataDir)).filter((x) => x.endsWith('.json')).sort();
await writeFile(
  path.join(dataDir, 'index.ts'),
  `// Generated by scripts/prospect.mjs. Lists every prospect page; edit by re-running the script.
import type { Prospect } from './types';
${files.map((f, i) => `import p${i} from './${f}';`).join('\n')}${files.length ? '\n' : ''}
export const prospects: Prospect[] = [${files.map((_, i) => `p${i}`).join(', ')}];
`,
);
console.log(removed ? `${removed} expired draft(s) removed.` : 'Nothing expired.');
